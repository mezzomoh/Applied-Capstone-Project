def interpretar_kmeans(X_transformed, labels, scaler=None, feature_names=None, nome_cluster="KMeans"):
    """
    Interpretação robusta de clusters KMeans.
    - Salva interpretação em master_log['sumario_execucao'].
    - Também concatena em 'clusters_interpretacao_texto_completo' para compatibilidade.
    """
    try:
        import numpy as _np
        from collections import Counter

        X = _np.asarray(X_transformed)
        labels = _np.asarray(labels)
        cluster_order = sorted(_np.unique(labels))
        n_clusters = int(_np.unique(labels).size)
        le_counts = Counter(labels)
        total = X.shape[0] if X.ndim == 2 else len(labels)

        centroids_trans = _np.vstack([X[labels == k].mean(axis=0) for k in cluster_order])
        if scaler is not None:
            try:
                centroids_orig = scaler.inverse_transform(centroids_trans)
            except Exception:
                centroids_orig = centroids_trans.copy()
        else:
            centroids_orig = centroids_trans.copy()

        n_features = centroids_orig.shape[1]
        if feature_names is None or len(feature_names) != n_features:
            feature_names = [f"f{i}" for i in range(n_features)]

        overall_mean = centroids_orig.mean(axis=0)
        interpretacoes = {}
        texto_completo = [f"Interpretação automática: {nome_cluster} — {n_clusters} clusters sobre {total} amostras."]

        for idx_i, centroid in enumerate(centroids_orig):
            k = cluster_order[idx_i]
            ksize = int(le_counts.get(k, 0))
            diffs = centroid - overall_mean
            idx_sorted = _np.argsort(_np.abs(diffs))[::-1]
            top_feats = [(feature_names[j], float(centroid[j]), float(diffs[j])) for j in idx_sorted[:3]]

            desc = {
                'cluster_id': int(k),
                'n_members': ksize,
                'centroid_values': {feature_names[j]: float(centroid[j]) for j in range(n_features)},
                'top_features_by_diff': [
                    {'feature': f, 'centroid': round(c, 4), 'delta_vs_mean': round(d, 4)} for f, c, d in top_feats
                ]
            }

            primary_feat, primary_val, primary_delta = top_feats[0]
            suggested_label = f"{primary_feat} mais baixa" if primary_delta < 0 else f"{primary_feat} mais alta"
            desc['suggested_label'] = suggested_label

            texto = (
                f"Cluster {k}: {ksize} UCs. Centro: " +
                ", ".join([f"{f}={desc['centroid_values'][f]:.4f}" for f in feature_names]) +
                ". Principais drivers: " +
                ", ".join([f'"{tf["feature"]}" (Δ {tf["delta_vs_mean"]:.4f})' for tf in desc['top_features_by_diff']]) +
                f". Rótulo sugerido: '{suggested_label}'."
            )
            texto_completo.append(texto)
            interpretacoes[f"cluster_{k}"] = desc

        summary_text = "\n".join(texto_completo)
        key_log = f"interpretacao_{nome_cluster.replace(' ', '_')}"
        master_log['sumario_execucao'][key_log] = {
            'text': summary_text,
            'details': interpretacoes
        }

        # Compatibilidade com versão original (texto único de clusters)
        prev = master_log['sumario_execucao'].get('clusters_interpretacao_texto_completo')
        if prev:
            master_log['sumario_execucao']['clusters_interpretacao_texto_completo'] = prev + "\n\n" + summary_text
        else:
            master_log['sumario_execucao']['clusters_interpretacao_texto_completo'] = summary_text

        logging.info(f"Interpretação de clusters gerada e salva em master_log['sumario_execucao']['{key_log}']")
        print("\n[Interpretação automática dos clusters]")
        print(summary_text)
        return {'text': summary_text, 'details': interpretacoes}

    except Exception as e:
        logging.warning(f"Falha em interpretar KMeans ({nome_cluster}): {e}")
        return None


