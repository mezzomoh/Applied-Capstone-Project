# Função: calcular_indicadores_agregados (CONSOLIDADA)
def calcular_indicadores_agregados(df_detalhado):
    """
    Cria df_mensal_agregado e df_agregado por UC com métricas essenciais.
    - Usa TU_clipado como base quando disponível.
    - Mantém NomeContratante_Normalizado / NomeContratante.
    Retorna: df_agregado, df_mensal
    """
    master_log['partes_executadas'].append('calcular_indicadores_agregados')
    df = df_detalhado.copy()

    # garantir Cod_UnidadeConsumidora string
    if 'Cod_UnidadeConsumidora' not in df.columns:
        raise ValueError("Coluna 'Cod_UnidadeConsumidora' inexistente no df_detalhado.")
    df['Cod_UnidadeConsumidora'] = df['Cod_UnidadeConsumidora'].astype(str)

    # garantir NomeContratante_Normalizado
    if 'NomeContratante_Normalizado' not in df.columns:
        if 'NomeContratante' in df.columns and 'mapa_orgaos' in globals():
            def _normalize_nome(n):
                try:
                    if pd.isna(n):
                        return n
                    s = str(n).upper().strip()
                    for patt, tgt in mapa_orgaos.items():
                        try:
                            if re.search(patt, s):
                                return tgt
                        except Exception:
                            continue
                    return s
                except Exception:
                    return str(n)
            df['NomeContratante_Normalizado'] = df['NomeContratante'].apply(_normalize_nome)
        else:
            df['NomeContratante_Normalizado'] = df.get('NomeContratante', 'N/A')

    # preparar datas de referência
    if 'periodo_referencia_dt' not in df.columns:
        if 'periodo_mes_ord' in df.columns:
            df['periodo_referencia_dt'] = pd.to_datetime(df['periodo_mes_ord'], errors='coerce')
        elif 'DataPosicao' in df.columns:
            df['periodo_referencia_dt'] = pd.to_datetime(df['DataPosicao'], errors='coerce')
        else:
            df['periodo_referencia_dt'] = pd.NaT

    df['periodo_mes_ord'] = pd.to_datetime(df['periodo_referencia_dt'], errors='coerce')
    df['periodo_mes'] = df['periodo_mes_ord'].dt.to_period('M').dt.to_timestamp('M')

    # converter colunas numéricas essenciais
    num_cols = [
        'QtdConsumo', 'QtdDemandaContratada', 'EP_ajustado',
        'custo_ultrapassagem_est', 'valor_unitario_limpo',
        'valor_liquido', 'VMe'
    ]
    for c in num_cols:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors='coerce')

    # --- 1) Agregação Mensal por UC ---
    def agg_func_mensal(g):
        # preferir QtdDemandaContratada_preenchida
        if 'QtdDemandaContratada_preenchida' in g.columns:
            qtd_dem_selected = _mode_or_max(g['QtdDemandaContratada_preenchida'])
        else:
            qtd_dem_selected = _mode_or_max(g.get('QtdDemandaContratada', pd.Series(dtype=float)))

        return pd.Series({
            'QtdConsumo_soma': g.get('QtdConsumo', pd.Series(dtype=float)).sum(min_count=1),
            'QtdDemanda_selecionada': qtd_dem_selected,
            'valor_unitario_wavg': _wavg_series(
                g.get('valor_unitario_limpo', pd.Series(dtype=float)),
                g.get('QtdConsumo', pd.Series(dtype=float))
            ),
            'EP_ajustado_soma': g.get('EP_ajustado', pd.Series(dtype=float)).sum(min_count=1),
            'custo_ultrapassagem_soma': g.get('custo_ultrapassagem_est', pd.Series(dtype=float)).sum(min_count=1),
            'TU_media_mensal': _wavg_series(
                g.get('TU_clipado', pd.Series(dtype=float)),
                g.get('QtdConsumo', pd.Series(dtype=float))
            ),
            'TU_media_original_mensal': _wavg_series(
                g.get('TU_original', pd.Series(dtype=float)),
                g.get('QtdConsumo', pd.Series(dtype=float))
            ),
            'n_registros': int(len(g)),
            'NomeContratante': g.get('NomeContratante_Normalizado',
                                     g.get('NomeContratante', pd.Series(dtype=object))
                                     ).iloc[0] if len(g) > 0 else None
        })

    df_mensal = (
        df.groupby(['Cod_UnidadeConsumidora', 'periodo_mes', 'periodo_mes_ord'], dropna=False)
          .apply(agg_func_mensal)
          .reset_index()
    )

    # preencher TU_media_mensal faltantes por média por UC
    if 'TU_media_mensal' in df_mensal.columns:
        df_mensal['TU_media_mensal'] = df_mensal['TU_media_mensal'].fillna(
            df_mensal.groupby('Cod_UnidadeConsumidora')['TU_media_mensal'].transform('mean')
        )

    # --- 2) Agregação por UC (Master) ---
    agg_dict = {
        'TU_media_geral': ('TU_clipado', 'mean'),
        'TU_std_geral': ('TU_clipado', 'std'),
        'TU_media_original': ('TU_original', 'mean'),
        'contagem_meses_total': ('periodo_mes', 'nunique'),
        'EP_ajustado_soma_total': ('EP_ajustado', 'sum'),
        'EP_ajustado_media': ('EP_ajustado', 'mean'),
        'custo_ultrapassagem_soma_total': ('custo_ultrapassagem_est', 'sum'),
        'QtdDemanda_modo': (
        'QtdDemandaContratada_preenchida' if 'QtdDemandaContratada_preenchida' in df.columns else 'QtdDemandaContratada',
        _mode_or_max),
        'QtdConsumo_media': ('QtdConsumo', 'mean'),
        'QtdConsumo_soma_total': ('QtdConsumo', 'sum'),
        'valor_liquido_soma_total': ('valor_liquido', 'sum'),
        'valor_unitario_limpo_media': ('valor_unitario_limpo', 'mean'),
        'valor_unitario_limpo_std': ('valor_unitario_limpo', 'std'),
        'NomeContratante': ('NomeContratante_Normalizado', 'first')
    }

    agg_kwargs = {}
    for k, v in agg_dict.items():
        if isinstance(v, tuple):
            col_name = v[0]
            if col_name in df.columns:
                agg_kwargs[k] = v
        else:
            agg_kwargs[k] = v

    df_agregado = df.groupby('Cod_UnidadeConsumidora').agg(**agg_kwargs).reset_index()

    # calculos derivados
    with np.errstate(divide='ignore', invalid='ignore'):
        df_agregado['CV_TU'] = df_agregado['TU_std_geral'] / df_agregado['TU_media_geral']
        df_agregado['CV_TU'] = df_agregado['CV_TU'].replace([np.inf, -np.inf], 0).fillna(0.0)

    # contagem_meses_validos_tu, pct_meses_abaixo_0_9 e slope_tu_mensal a partir de df_mensal
    try:
        g_uc = df_mensal.groupby('Cod_UnidadeConsumidora')
        contagem_meses_validos = g_uc['TU_media_mensal'].count().rename('contagem_meses_validos_tu')
        pct_meses_abaixo_0_9 = (
            g_uc['TU_media_mensal'].apply(lambda x: (x < 0.9).sum()) /
            contagem_meses_validos.replace(0, np.nan)
        ).rename('pct_meses_abaixo_0_9')
        slope_tu = g_uc.apply(_calcular_slope_tu).rename('slope_tu_mensal')

        df_agregado = df_agregado.merge(contagem_meses_validos, on='Cod_UnidadeConsumidora', how='left')
        df_agregado = df_agregado.merge(pct_meses_abaixo_0_9, on='Cod_UnidadeConsumidora', how='left')
        df_agregado = df_agregado.merge(slope_tu, on='Cod_UnidadeConsumidora', how='left')
    except Exception as e:
        logging.warning(f"Erro ao calcular pct_meses/slope: {e}")
        master_log['notas'].append(f"Erro pct_meses/slope: {e}")

    # preenchimentos e defaults
    df_agregado['contagem_meses_validos_tu'] = (
        df_agregado.get('contagem_meses_validos_tu',
                        df_agregado.get('contagem_meses_total', 0))
        .fillna(0).astype(int)
    )
    df_agregado['pct_meses_abaixo_0_9'] = df_agregado.get('pct_meses_abaixo_0_9', 0.0).fillna(0.0)
    df_agregado['slope_tu_mensal'] = df_agregado.get('slope_tu_mensal', 0.0).fillna(0.0)
    df_agregado['TU_std_geral'] = df_agregado['TU_std_geral'].fillna(0.0)
    df_agregado['valor_unitario_limpo_std'] = df_agregado.get('valor_unitario_limpo_std', 0.0).fillna(0.0)
    if 'valor_unitario_limpo_media' in df_agregado.columns:
        df_agregado['valor_unitario_limpo_media'] = df_agregado['valor_unitario_limpo_media'].fillna(
            df['valor_unitario_limpo'].mean() if 'valor_unitario_limpo' in df.columns else 0.0
        )

    # Faixa TU
    def faixa_tu_mean(x):
        if pd.isna(x):
            return 'NA'
        elif x < 0.95:
            return 'A_Subutilizacao'
        elif x <= 1.05:
            return 'B_Otimo'
        else:
            return 'C_Ultrapassagem'

    df_agregado['Faixa_TU_mean'] = df_agregado['TU_media_geral'].apply(faixa_tu_mean)

    # Skew / Kurtosis por UC (defensivo)
    try:
        skew_tu = df.groupby('Cod_UnidadeConsumidora')['TU_clipado'].skew().rename('TU_skew_geral')
        kurt_tu = df.groupby('Cod_UnidadeConsumidora')['TU_clipado'].apply(lambda x: x.kurtosis()).rename('TU_kurt_geral')
        stats_sk = pd.concat([skew_tu, kurt_tu], axis=1).reset_index()
        df_agregado = df_agregado.merge(stats_sk, on='Cod_UnidadeConsumidora', how='left')
        df_agregado['TU_skew_geral'] = df_agregado['TU_skew_geral'].fillna(0.0)
        df_agregado['TU_kurt_geral'] = df_agregado['TU_kurt_geral'].fillna(0.0)
    except Exception as e:
        logging.warning(f"Falha ao calcular skew/kurt per UC: {e}")
        master_log['notas'].append(f"skew_kurt_per_uc falhou: {e}")

    logging.info(f"Agregação concluída: {len(df_agregado)} UCs, {len(df_mensal)} registros UC/mês.")
    return df_agregado, df_mensal


