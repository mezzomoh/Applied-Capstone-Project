# ------------------------------------------------------
def executar_analise_sensibilidade_ep(df_detalhado, df_agregado_final=None):
    """
    Análise de sensibilidade do EP substituindo a tarifa (real ou imputada) em TODAS as faturas.
    """
    master_log['partes_executadas'].append('executar_analise_sensibilidade_ep_substituir_tarifa')
    logging.info("Iniciando Análise de Sensibilidade do EP (substituindo tarifa em TODAS as faturas)...")

    try:
        tarifa_real_usada = master_log['sumario_execucao'].get('VUL_media_calculada_imputacao')

        if tarifa_real_usada is None or (isinstance(tarifa_real_usada, (float, int)) and np.isnan(tarifa_real_usada)):
            logging.warning("VUL_media_calculada_imputacao não encontrada no log. Recalculando (mediana dos VUL válidos)...")
            if 'ValorConsumidoUnitario' in df_detalhado.columns:
                if 'VUL_foi_imputado' in df_detalhado.columns:
                    mascara_validos = ~df_detalhado['VUL_foi_imputado']
                else:
                    mascara_validos = pd.Series(True, index=df_detalhado.index)
                tarifa_por_dados = df_detalhado.loc[mascara_validos, 'ValorConsumidoUnitario']
                if tarifa_por_dados.dropna().size > 0:
                    tarifa_real_usada = float(tarifa_por_dados.median())
                    logging.info(f"Tarifa de imputação obtida (Mediana VUL): R$ {tarifa_real_usada:.4f}")
                    master_log['sumario_execucao']['VUL_media_calculada_imputacao'] = round(tarifa_real_usada, 4)
                else:
                    tarifa_real_usada = 0.80
                    logging.warning("Não foi possível calcular VUL a partir dos dados. Usando fallback R$ 0.80")
                    master_log['sumario_execucao']['VUL_media_calculada_imputacao'] = round(tarifa_real_usada, 4)
                    master_log['sumario_execucao']['VUL_imputacao_usou_fallback'] = True
            else:
                tarifa_real_usada = 0.80
                master_log['sumario_execucao']['VUL_media_calculada_imputacao'] = round(tarifa_real_usada, 4)
                master_log['sumario_execucao']['VUL_imputacao_usou_fallback'] = True
        else:
            tarifa_real_usada = float(tarifa_real_usada)
            logging.info(f"Tarifa de imputação usada (do sumario): R$ {tarifa_real_usada:.4f}")

        for col in ['QtdConsumo', 'valor_liquido']:
            if col not in df_detalhado.columns:
                raise ValueError(f"Coluna obrigatória '{col}' não encontrada em df_detalhado.")
        df = df_detalhado.copy()
        df['QtdConsumo'] = pd.to_numeric(df['QtdConsumo'], errors='coerce').fillna(0.0)
        df['valor_liquido'] = pd.to_numeric(df['valor_liquido'], errors='coerce').fillna(0.0)

        lower = max(0.001, tarifa_real_usada * 0.01)
        upper = tarifa_real_usada * 3.0
        tarifas_simuladas = np.linspace(lower, upper, 30)

        resultados_sensibilidade = []

        for tarifa_ref_sim in tarifas_simuladas:
            df['EP_sim'] = df['valor_liquido'] - df['QtdConsumo'] * tarifa_ref_sim
            ep_por_uc = df.groupby('Cod_UnidadeConsumidora')['EP_sim'].sum()
            desperdicio_total_sim = float(ep_por_uc[ep_por_uc > 0].sum())
            inconsistencia_total_sim = float(ep_por_uc[ep_por_uc < 0].sum())
            total_sim = float(ep_por_uc.sum())

            resultados_sensibilidade.append({
                'tarifa_ref_simulada': tarifa_ref_sim,
                'EP_Total_Agregado': total_sim,
                'Desperdício_Total (EP Positivo)': desperdicio_total_sim,
                'Inconsistência_Total (EP Negativo)': inconsistencia_total_sim
            })

        df_plot_sensibilidade = pd.DataFrame(resultados_sensibilidade)

        # Plot
        fig, ax = plt.subplots(figsize=(12, 7))
        ax.plot(
            df_plot_sensibilidade['tarifa_ref_simulada'],
            df_plot_sensibilidade['EP_Total_Agregado'],
            marker='o',
            label='EP Total Agregado'
        )
        ax.plot(
            df_plot_sensibilidade['tarifa_ref_simulada'],
            df_plot_sensibilidade['Desperdício_Total (EP Positivo)'],
            marker='o',
            label='Desperdício Total (EP Positivo)'
        )
        ax.plot(
            df_plot_sensibilidade['tarifa_ref_simulada'],
            df_plot_sensibilidade['Inconsistência_Total (EP Negativo)'],
            marker='x',
            label='Inconsistência Total (EP Negativo)'
        )

        ax.axvline(
            x=tarifa_real_usada,
            color='red',
            linestyle='--',
            label=f'Tarifa de Referência Imputada (R$ {tarifa_real_usada:.3f})'
        )
        ax.axhline(y=0, color='black', linestyle='-', linewidth=0.5)

        ax.set_title('Análise de Sensibilidade do EP substituindo a Tarifa (todas as faturas)')
        ax.set_xlabel('Tarifa de Referência (R$) usada para imputação (simulada)')
        ax.set_ylabel('Valor Total Simulado (R$)')
        ax.legend()
        ax.grid(True)
        ax.get_yaxis().set_major_formatter(
            plt.FuncFormatter(lambda x, p: f'R$ {x/1_000_000:.0f}M')
        )

        salvar_figura(fig, "analise_sensibilidade_ep_substituir_tarifa")
        plt.close(fig)

        try:
            path_out = DIRETORIO_PACOTE / "analise_sensibilidade_ep_substituir_tarifa.csv"
            path_out.parent.mkdir(parents=True, exist_ok=True)
            df_plot_sensibilidade.to_csv(path_out, sep=';', index=False, encoding='utf-8-sig')
            master_log['arquivos_de_dados_criados'].append(str(path_out))
        except Exception as e_save:
            logging.warning(f"Não foi possível salvar CSV de sensibilidade (substituir tarifa): {e_save}")
            master_log['notas'].append(f"Falha ao salvar CSV sensibilidade (substituir tarifa): {e_save}")

        master_log['sumario_execucao']['df_sensibilidade_ep_substituir_tarifa'] = df_plot_sensibilidade.to_dict(orient='list')
        logging.info("Análise de Sensibilidade (substituir tarifa) concluída e resultados salvos.")

        return df_plot_sensibilidade

    except Exception as e:
        logging.error(f"Falha na Análise de Sensibilidade (substituir tarifa): {e}")
        master_log['notas'].append(f"Falha na Análise de Sensibilidade (substituir tarifa): {e}")
        return None


