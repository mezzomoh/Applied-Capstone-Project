    with np.errstate(divide='ignore', invalid='ignore'):
        df['demanda_kw_estimada'] = df['QtdConsumo'] / df['horas_operacionais']
        df['TU'] = df['demanda_kw_estimada'] / df['QtdDemandaContratada_preenchida']
    df.loc[~np.isfinite(df['TU']), 'TU'] = np.nan
    df.loc[df['QtdDemandaContratada_preenchida'] <= 0, 'TU'] = np.nan

