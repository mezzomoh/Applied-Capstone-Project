def _parse_numeric_series(s: pd.Series):
    """ Tenta converter uma série para numérico (robusto). """
    s_orig = s.astype(str).str.strip().replace({'': None, 'nan': None})
    v1 = pd.to_numeric(s_orig.str.replace(',', '.', regex=False), errors='coerce')
    nonnull_v1 = v1.notna().sum()
    s2 = s_orig.str.replace('.', '', regex=False).str.replace(',', '.', regex=False)
    v2 = pd.to_numeric(s2, errors='coerce')
    nonnull_v2 = v2.notna().sum()
    return v2 if nonnull_v2 > nonnull_v1 else v1

def _to_datetime_safe(series):
    """ Converte para datetime (robusto). """
    out = pd.to_datetime(series, dayfirst=True, errors='coerce')
    if out.isna().all():
        out = pd.to_datetime(series, errors='coerce')
    return out

def _calcular_dias_uteis_vetorizado(starts, ends):
    """ Calcula dias úteis de forma vetorizada. """
    starts = pd.to_datetime(starts, errors='coerce')
    ends = pd.to_datetime(ends, errors='coerce')
    result = pd.Series(index=starts.index, dtype=float)
    valid_mask = starts.notna() & ends.notna() & (ends >= starts)
    if valid_mask.any():
        s_np_dt64 = starts.loc[valid_mask].values.astype('datetime64[D]')
        e_np_dt64 = ends.loc[valid_mask].values.astype('datetime64[D]')
        bd = np.busday_count(s_np_dt64, (e_np_dt64 + np.timedelta64(1, 'D')))
        result.loc[valid_mask] = bd.astype(float)
    return result

def _wavg_series(values, weights):
    """ Média ponderada robusta a NaNs. """
    values = np.asarray(values, dtype=float)
    weights = np.asarray(weights, dtype=float)
    mask = (~np.isnan(values)) & (~np.isnan(weights)) & (weights > 0)
    if mask.sum() == 0:
        return np.nan
    return (values[mask] * weights[mask]).sum() / weights[mask].sum()

def _mode_or_max(series):
    """ Retorna a moda; se empate, retorna o valor máximo entre os mais frequentes. """
    s = series.dropna()
    if s.empty:
        return np.nan
    modes = s.mode()
    if len(modes) == 1:
        return modes.iloc[0]
    counts = s.value_counts()
    top_count = counts.max()
    top_vals = counts[counts == top_count].index
    return max(top_vals)

def _minmax_safe(series, invert=False):
    """ Normalização Min-Max robusta a NaNs e divisão por zero. """
    s = pd.to_numeric(series, errors='coerce').replace([np.inf, -np.inf], np.nan)
    mn = s.min(skipna=True)
    mx = s.max(skipna=True)
    if pd.isna(mn) or pd.isna(mx) or mn == mx:
        return pd.Series(np.nan, index=s.index)
    out = (s - mn) / (mx - mn)
    return 1 - out if invert else out

def _calcular_slope_tu(g):
    """ Calcula a inclinação (slope) da série temporal de TU_media_mensal. """
    g = g.dropna(subset=['periodo_mes_ord', 'TU_media_mensal']).sort_values('periodo_mes_ord')
    if g.shape[0] < 2:
        return np.nan
    try:
        X = (g['periodo_mes_ord'].dt.year * 12 + g['periodo_mes_ord'].dt.month).astype(int).values.reshape(-1, 1)
        y = g['TU_media_mensal'].values.reshape(-1, 1)
        lr = LinearRegression().fit(X, y)
        return float(lr.coef_[0][0])
    except Exception:
        return np.nan

# (NOVA FUNÇÃO AUXILIAR PARA CÉLULA 7)
def _clip_tu_outliers_por_uc(s: pd.Series) -> pd.Series:
    """
    Aplica clipping de outliers em uma série (TU de uma UC)
    usando o método IQR (Q3 + 1.5 * IQR).
    """
    if s.count() < 5:
        return s

    Q1 = s.quantile(0.25)
    Q3 = s.quantile(0.75)
    IQR = Q3 - Q1

    if IQR == 0:
        return s

    limite_superior = Q3 + (IQR_MULTIPLIER * IQR)

    return s.clip(upper=limite_superior)

