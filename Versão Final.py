def gerar_ranking_modelE(df_agregado, MIN_OBSERVACOES_PARA_RANKING=None, pesos=None, *, min_obs=None):
    """
    Gera o score composto Modelo E e o ranking (rank_modelE).
    Compatível com min_obs e MIN_OBSERVACOES_PARA_RANKING.
    """
    master_log['partes_executadas'].append('gerar_ranking_modelE')

    if min_obs is not None:
        min_obs_val = int(min_obs)
    elif MIN_OBSERVACOES_PARA_RANKING is not None:
        min_obs_val = int(MIN_OBSERVACOES_PARA_RANKING)
    else:
        min_obs_val = int(globals().get('MIN_OBSERVACOES_PARA_RANKING', 12))

    if pesos is None:
        pesos = globals().get(
            'PESOS_MODELO_E',
            {'tu': 1, 'ep': 1, 'ultrap': 1, 'std_tu': 1, 'pct_abaixo': 1, 'slope': 1}
        )

    df = df_agregado.copy()

    required = [
        'contagem_meses_validos_tu', 'TU_media_geral', 'EP_ajustado_soma_total',
        'custo_ultrapassagem_soma_total', 'TU_std_geral',
        'pct_meses_abaixo_0_9', 'slope_tu_mensal'
    ]
    for col in required:
        if col not in df.columns:
            df[col] = 0.0

    idx_incluidos = df['contagem_meses_validos_tu'].fillna(0) >= min_obs_val
    df_incluidos = df.loc[idx_incluidos].copy()

    if df_incluidos.empty:
        logging.warning(f"Nenhuma UC atendeu ao mínimo de {min_obs_val} observações. Ranking não gerado.")
        df['score_composto_modelE'] = np.nan
        df['rank_modelE'] = np.nan
        return df

    logging.info(f"{len(df_incluidos)} UCs incluídas no ranking (min_obs={min_obs_val})")

    df_incluidos['comp_tu'] = _minmax_safe(1 - (df_incluidos['TU_media_geral'] - 1).abs(), invert=False)
    df_incluidos['comp_ep'] = _minmax_safe(df_incluidos['EP_ajustado_soma_total'], invert=True)
    df_incluidos['comp_ultrap'] = _minmax_safe(df_incluidos['custo_ultrapassagem_soma_total'], invert=True)
    df_incluidos['comp_std_tu'] = _minmax_safe(df_incluidos['TU_std_geral'], invert=True)
    df_incluidos['comp_pct_abaixo'] = _minmax_safe(df_incluidos['pct_meses_abaixo_0_9'], invert=True)
    df_incluidos['comp_slope'] = _minmax_safe(df_incluidos['slope_tu_mensal'], invert=False)

    comp_cols = [
        'comp_tu', 'comp_ep', 'comp_ultrap',
        'comp_std_tu', 'comp_pct_abaixo', 'comp_slope'
    ]
    df_incluidos[comp_cols] = df_incluidos[comp_cols].fillna(0.0)

    df_incluidos['score_composto_modelE'] = (
        df_incluidos['comp_tu'] * float(pesos.get('tu', 1.0)) +
        df_incluidos['comp_ep'] * float(pesos.get('ep', 1.0)) +
        df_incluidos['comp_ultrap'] * float(pesos.get('ultrap', 1.0)) +
        df_incluidos['comp_std_tu'] * float(pesos.get('std_tu', 1.0)) +
        df_incluidos['comp_pct_abaixo'] * float(pesos.get('pct_abaixo', 1.0)) +
        df_incluidos['comp_slope'] * float(pesos.get('slope', 1.0))
    )

    df_incluidos['rank_modelE'] = df_incluidos['score_composto_modelE'].rank(
        method='min', ascending=False
    )

    cols_ranking = comp_cols + ['score_composto_modelE', 'rank_modelE']
    df = df.merge(
        df_incluidos[['Cod_UnidadeConsumidora'] + cols_ranking],
        on='Cod_UnidadeConsumidora',
        how='left'
    )
    return df

