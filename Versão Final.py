    master_log['partes_executadas'].append('carregar_e_preparar_dados')

    if (not force_reload) and caminho_cache.exists():
        logging.info(f"Carregando dados do cache: {caminho_cache}")
        return pd.read_parquet(caminho_cache)

    logging.info(f"Lendo CSV (pode levar tempo): {caminho_csv}")
    try:
        df = pd.read_csv(caminho_csv, sep=';', encoding='latin-1', low_memory=False)
    except Exception as e:
        logging.error(f"Erro fatal ao ler CSV: {e}")
        raise

    df.columns = [c.strip() for c in df.columns]

    # Garantir dtype consistente para Cod_UnidadeConsumidora (evita merges entre int/str)
    if 'Cod_UnidadeConsumidora' in df.columns:
        df['Cod_UnidadeConsumidora'] = df['Cod_UnidadeConsumidora'].astype(str).str.strip()

    # --- Transformações (TCC 3.3) ---
    num_cols = [
        'QtdConsumo', 'ValorTotal', 'ValorMulta', 'ValorJuros',
        'ValorCorrecaoMonetaria', 'ValorConsumidoUnitario', 'QtdDemandaContratada'
    ]
    for c in num_cols:
        if c in df.columns:
            df[c] = _parse_numeric_series(df[c]).astype(float)
            master_log['sumario_execucao'][f'n_validos_{c}'] = int(df[c].notna().sum())

    df['DataInicioConsumo_dt'] = _to_datetime_safe(df.get('DataInicioConsumo'))
    df['DataFimConsumo_dt'] = _to_datetime_safe(df.get('DataFimConsumo'))
    df['periodo_referencia_dt'] = df['DataInicioConsumo_dt'].fillna(df['DataFimConsumo_dt'])
    df['periodo_mes'] = df['periodo_referencia_dt'].dt.to_period('M').astype(str)
    df['periodo_mes_ord'] = pd.to_datetime(df['periodo_mes'], errors='coerce')

    # Dias úteis (TCC 3.4.1)
    df['dias_uteis_fatura'] = _calcular_dias_uteis_vetorizado(df['DataInicioConsumo_dt'], df['DataFimConsumo_dt'])
    df['dias_uteis_fatura_preenchido'] = df['dias_uteis_fatura'].fillna(DIAS_UTEIS_FALLBACK)
    df.loc[df['dias_uteis_fatura_preenchido'] <= 0, 'dias_uteis_fatura_preenchido'] = DIAS_UTEIS_FALLBACK
    df['horas_operacionais'] = df['dias_uteis_fatura_preenchido'] * HORAS_OPERACIONAIS_POR_DIA

